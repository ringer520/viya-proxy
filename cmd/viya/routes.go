package main

import (
	"net/http"
	"time"

	"viya/internal/web"
)

// registerRoutes is the single list of API endpoints. main() only assembles the
// server around it, so adding a route no longer means editing a 200-line block
// in the middle of process startup.
func (a *App) registerRoutes(mux *http.ServeMux) {
	mux.HandleFunc("GET /api/v1/health", func(w http.ResponseWriter, r *http.Request) {
		writeJSON(w, 200, map[string]any{"ok": true, "caddy_ready": a.isCaddyReady(), "time": time.Now().UTC()})
	})
	mux.Handle("GET /api/v1/layer4-rules", a.requireAuth(http.HandlerFunc(a.listLayer4Rules)))
	mux.Handle("POST /api/v1/layer4-rules/check", a.requireAuth(http.HandlerFunc(a.checkForwardPort)))
	mux.Handle("POST /api/v1/layer4-rules", a.requireAuth(http.HandlerFunc(a.createLayer4Rule)))
	mux.Handle("PUT /api/v1/layer4-rules/{id}", a.requireAuth(http.HandlerFunc(a.updateLayer4Rule)))
	mux.Handle("DELETE /api/v1/layer4-rules/{id}", a.requireAuth(http.HandlerFunc(a.deleteLayer4Rule)))
	mux.Handle("GET /api/v1/layer4-rules/{id}/logs", a.requireAuth(http.HandlerFunc(a.layer4RuleLogs)))
	mux.Handle("GET /api/v1/ddns-records", a.requireAuth(http.HandlerFunc(a.listDDNSRecords)))
	mux.Handle("GET /api/v1/network-interfaces", a.requireAuth(http.HandlerFunc(a.listNetworkInterfaces)))
	mux.Handle("POST /api/v1/ddns-records", a.requireAuth(http.HandlerFunc(a.createDDNSRecord)))
	mux.Handle("PUT /api/v1/ddns-records/{id}", a.requireAuth(http.HandlerFunc(a.updateDDNSRecord)))
	mux.Handle("DELETE /api/v1/ddns-records/{id}", a.requireAuth(http.HandlerFunc(a.deleteDDNSRecord)))
	mux.Handle("POST /api/v1/ddns-records/{id}/run", a.requireAuth(http.HandlerFunc(a.runDDNSRecord)))
	mux.Handle("GET /api/v1/ddns-records/{id}/runs", a.requireAuth(http.HandlerFunc(a.listDDNSRuns)))
	mux.Handle("GET /api/v1/custom-certificates", a.requireAuth(http.HandlerFunc(a.listCustomCertificates)))
	mux.Handle("POST /api/v1/custom-certificates", a.requireAuth(http.HandlerFunc(a.createCustomCertificate)))
	mux.Handle("DELETE /api/v1/custom-certificates/{id}", a.requireAuth(http.HandlerFunc(a.deleteCustomCertificate)))
	mux.Handle("GET /api/v1/logs", a.requireAuth(http.HandlerFunc(a.recentLogs)))
	mux.Handle("GET /api/v1/logs/program", a.requireAuth(http.HandlerFunc(a.recentProgramLogs)))
	mux.Handle("GET /api/v1/logs/settings", a.requireAuth(http.HandlerFunc(a.getLogSettings)))
	mux.Handle("PUT /api/v1/logs/settings", a.requireAuth(http.HandlerFunc(a.updateLogSettings)))
	mux.Handle("PATCH /api/v1/layer4-rules/{id}/enabled", a.requireAuth(http.HandlerFunc(a.toggleLayer4Enabled)))
	mux.Handle("GET /api/v1/proxy-hosts/error-locations", a.requireAuth(http.HandlerFunc(a.webErrorLocations)))
	mux.Handle("GET /api/v1/proxy-hosts/traffic", a.requireAuth(http.HandlerFunc(a.siteTraffic)))
	mux.Handle("GET /api/v1/layer4-rules/traffic", a.requireAuth(http.HandlerFunc(a.l4Traffic)))
	mux.Handle("GET /api/v1/proxy-hosts/health", a.requireAuth(http.HandlerFunc(a.upstreamHealthReport)))
	mux.Handle("POST /api/v1/proxy-hosts/health", a.requireAuth(http.HandlerFunc(a.forceProbeUpstreams)))
	mux.Handle("GET /api/v1/alert-settings", a.requireAuth(http.HandlerFunc(a.getAlertSettings)))
	mux.Handle("PUT /api/v1/alert-settings", a.requireAuth(http.HandlerFunc(a.updateAlertSettings)))
	mux.Handle("POST /api/v1/alert-settings/test", a.requireAuth(http.HandlerFunc(a.testAlertSettings)))
	mux.Handle("GET /api/v1/certificates/expiring", a.requireAuth(http.HandlerFunc(a.expiringCertificates)))
	mux.Handle("GET /api/v1/proxy-hosts/{id}/logs", a.requireAuth(http.HandlerFunc(a.siteAccessLogs)))
	// Static-site file management (list/upload/download/delete/mkdir). Writes
	// are limited to the managed sites tree and stay admin-only via requireAuth.
	mux.Handle("GET /api/v1/proxy-hosts/{id}/files", a.requireAuth(http.HandlerFunc(a.listSiteFiles)))
	mux.Handle("GET /api/v1/proxy-hosts/{id}/files/text", a.requireAuth(http.HandlerFunc(a.siteFileText)))
	mux.Handle("PUT /api/v1/proxy-hosts/{id}/files/text", a.requireAuth(http.HandlerFunc(a.siteFileText)))
	mux.Handle("GET /api/v1/proxy-hosts/{id}/files/stat", a.requireAuth(http.HandlerFunc(a.siteFileStats)))
	mux.Handle("GET /api/v1/proxy-hosts/{id}/files/download", a.requireAuth(http.HandlerFunc(a.downloadSiteFile)))
	mux.Handle("POST /api/v1/proxy-hosts/{id}/files/upload", a.requireAuth(http.HandlerFunc(a.uploadSiteFiles)))
	mux.Handle("POST /api/v1/proxy-hosts/{id}/files/mkdir", a.requireAuth(http.HandlerFunc(a.mkdirSiteFile)))
	mux.Handle("DELETE /api/v1/proxy-hosts/{id}/files", a.requireAuth(http.HandlerFunc(a.deleteSiteFile)))
	// Read-only inventory of static sites and file shares for the hub page.
	mux.Handle("GET /api/v1/file-shares", a.requireAuth(http.HandlerFunc(a.listFileShares)))
	// WebDAV share configuration (single files-type host).
	mux.Handle("GET /api/v1/webdav-settings", a.requireAuth(http.HandlerFunc(a.getWebDAVSettings)))
	mux.Handle("PUT /api/v1/webdav-settings", a.requireAuth(http.HandlerFunc(a.saveWebDAVSettings)))
	mux.Handle("GET /api/v1/logs/stream", a.requireAuth(http.HandlerFunc(a.streamLogs)))
	mux.Handle("GET /api/v1/ip-bans", a.requireAuth(http.HandlerFunc(a.listIPBans)))
	mux.Handle("POST /api/v1/ip-bans", a.requireAuth(http.HandlerFunc(a.saveIPBan)))
	mux.Handle("PUT /api/v1/ip-bans/{id}", a.requireAuth(http.HandlerFunc(a.saveIPBan)))
	mux.Handle("GET /api/v1/ban-policy", a.requireAuth(http.HandlerFunc(a.getBanPolicy)))
	mux.Handle("PUT /api/v1/ban-policy", a.requireAuth(http.HandlerFunc(a.updateBanPolicy)))
	mux.Handle("GET /api/v1/managed-certificates", a.requireAuth(http.HandlerFunc(a.listManagedCertificates)))
	mux.Handle("POST /api/v1/managed-certificates", a.requireAuth(http.HandlerFunc(a.requestCertificate)))
	mux.Handle("PUT /api/v1/managed-certificates/{id}", a.requireAuth(http.HandlerFunc(a.requestCertificate)))
	mux.Handle("GET /api/v1/system-metrics", a.requireAuth(http.HandlerFunc(a.systemMetrics)))
	mux.Handle("PATCH /api/v1/proxy-hosts/{id}/enabled", a.requireAuth(http.HandlerFunc(a.toggleHostEnabled)))
	mux.Handle("DELETE /api/v1/managed-certificates/{id}", a.requireAuth(http.HandlerFunc(a.deleteManagedCertificate)))
	mux.Handle("DELETE /api/v1/ip-bans/{id}", a.requireAuth(http.HandlerFunc(a.removeIPBan)))
	mux.Handle("GET /api/v1/version", a.requireAuth(http.HandlerFunc(a.versionInfoHandler)))
	mux.Handle("POST /api/v1/version/update", a.requireAuth(http.HandlerFunc(a.versionUpdateHandler)))
	mux.Handle("GET /api/v1/version/update/status", a.requireAuth(http.HandlerFunc(a.versionUpdateProgressHandler)))
	mux.HandleFunc("GET /api/v1/auth/status", a.authStatus)
	mux.HandleFunc("POST /api/v1/auth/setup", a.setupAdmin)
	mux.HandleFunc("POST /api/v1/auth/login", a.login)
	mux.Handle("POST /api/v1/auth/logout", a.requireAuth(http.HandlerFunc(a.logout)))
	mux.Handle("GET /api/v1/auth/me", a.requireAuth(http.HandlerFunc(a.me)))
	mux.Handle("GET /api/v1/auth/audit", a.requireAuth(http.HandlerFunc(a.listLoginAudit)))
	mux.Handle("GET /api/v1/panel/settings", a.requireAuth(http.HandlerFunc(a.getPanelSettings)))
	mux.Handle("GET /api/v1/panel/access", a.requireAuth(http.HandlerFunc(a.getPanelAccess)))
	mux.Handle("PUT /api/v1/panel/access", a.requireAuth(http.HandlerFunc(a.putPanelAccess)))
	mux.Handle("PUT /api/v1/panel/settings/port", a.requireAuth(http.HandlerFunc(a.updatePanelPort)))
	mux.Handle("POST /api/v1/auth/sessions/revoke-others", a.requireAuth(http.HandlerFunc(a.revokeOtherSessions)))
	mux.Handle("POST /api/v1/auth/password", a.requireAuth(http.HandlerFunc(a.changeAdminPassword)))
	mux.Handle("GET /api/v1/proxy-hosts", a.requireAuth(http.HandlerFunc(a.listHosts)))
	mux.Handle("POST /api/v1/config/apply", a.requireAuth(http.HandlerFunc(a.reapplyConfig)))
	mux.Handle("POST /api/v1/dns-providers/{id}/check", a.requireAuth(http.HandlerFunc(a.checkDNSProvider)))
	mux.Handle("GET /api/v1/dns-providers/{id}/usage", a.requireAuth(http.HandlerFunc(a.dnsProviderUsage)))
	mux.Handle("PATCH /api/v1/dns-providers/{id}/name", a.requireAuth(http.HandlerFunc(a.renameDNSProvider)))
	mux.Handle("GET /api/v1/dns-providers", a.requireAuth(http.HandlerFunc(a.listDNSProviders)))
	mux.Handle("GET /api/v1/dns-providers/{id}/zones", a.requireAuth(http.HandlerFunc(a.listDNSZones)))
	mux.Handle("POST /api/v1/dns-providers", a.requireAuth(http.HandlerFunc(a.createDNSProvider)))
	mux.Handle("PUT /api/v1/dns-providers/{id}", a.requireAuth(http.HandlerFunc(a.updateDNSProvider)))
	mux.Handle("DELETE /api/v1/dns-providers/{id}", a.requireAuth(http.HandlerFunc(a.deleteDNSProvider)))
	mux.Handle("POST /api/v1/proxy-hosts", a.requireAuth(http.HandlerFunc(a.createHost)))
	mux.Handle("POST /api/v1/proxy-hosts/test-upstream", a.requireAuth(http.HandlerFunc(a.testUpstream)))
	mux.Handle("PUT /api/v1/proxy-hosts/{id}", a.requireAuth(http.HandlerFunc(a.updateHost)))
	mux.Handle("GET /api/v1/certificate-inventory", a.requireAuth(http.HandlerFunc(a.certificateInventory)))
	mux.Handle("DELETE /api/v1/certificate-inventory/{domain}", a.requireAuth(http.HandlerFunc(a.deleteAutomaticCertificate)))
	mux.Handle("POST /api/v1/config/export", a.requireAuth(http.HandlerFunc(a.exportConfiguration)))
	mux.Handle("POST /api/v1/config/import/inspect", a.requireAuth(http.HandlerFunc(a.inspectConfiguration)))
	mux.Handle("POST /api/v1/config/import", a.requireAuthUnlocked(http.HandlerFunc(a.importConfiguration)))
	mux.Handle("POST /api/v1/auth/username", a.requireAuth(http.HandlerFunc(a.changeUsername)))
	mux.Handle("GET /api/v1/users", a.requireAuth(http.HandlerFunc(a.listUsers)))
	mux.Handle("POST /api/v1/users", a.requireAuth(http.HandlerFunc(a.createUser)))
	mux.Handle("PUT /api/v1/users/{id}", a.requireAuth(http.HandlerFunc(a.updateUser)))
	mux.Handle("DELETE /api/v1/users/{id}", a.requireAuth(http.HandlerFunc(a.deleteUser)))
	mux.Handle("GET /api/v1/web-listeners", a.requireAuth(http.HandlerFunc(a.getWebListeners)))
	mux.Handle("PUT /api/v1/web-listeners", a.requireAuth(http.HandlerFunc(a.saveWebListeners)))
	mux.Handle("GET /api/v1/web-listeners/check", a.requireAuth(http.HandlerFunc(a.checkWebListener)))
	mux.Handle("PATCH /api/v1/ddns-records/{id}/enabled", a.requireAuth(http.HandlerFunc(a.toggleDDNSEnabled)))
	mux.Handle("DELETE /api/v1/proxy-hosts/{id}", a.requireAuth(http.HandlerFunc(a.deleteHost)))
	mux.Handle("POST /api/v1/security-defaults/preview", a.requireAuth(http.HandlerFunc(a.previewSecurityPolicy)))
	mux.Handle("GET /api/v1/security-defaults", a.requireAuth(http.HandlerFunc(a.getSecurityDefaults)))
	mux.Handle("PUT /api/v1/security-defaults/global", a.requireAuth(http.HandlerFunc(a.saveSecurityGlobal)))
	mux.Handle("PUT /api/v1/security-defaults/domain/{domain}", a.requireAuth(http.HandlerFunc(a.saveSecurityDomain)))
	mux.Handle("DELETE /api/v1/security-defaults/domain/{domain}", a.requireAuth(http.HandlerFunc(a.deleteSecurityDomain)))
	mux.Handle("POST /api/v1/security-defaults/apply", a.requireAuth(http.HandlerFunc(a.applySecurityDefaults)))
	mux.Handle("GET /api/v1/config/status", a.requireAuthUnlocked(http.HandlerFunc(a.configurationStatus)))
	mux.Handle("POST /api/v1/config/rollback", a.requireAuth(http.HandlerFunc(a.rollbackConfiguration)))
	mux.Handle("GET /api/v1/proxy-hosts/{id}/diagnostics", a.requireAuth(http.HandlerFunc(a.diagnoseSite)))
	mux.Handle("PATCH /api/v1/proxy-hosts/{id}/metadata", a.requireAuth(http.HandlerFunc(a.updateSiteMetadata)))
	mux.Handle("POST /api/v1/panel/settings/confirm", a.requireAuth(http.HandlerFunc(a.confirmPanelAccess)))
	mux.Handle("GET /api/v1/storage", a.requireAuth(http.HandlerFunc(a.storageUsage)))
	mux.Handle("PUT /api/v1/storage/retention", a.requireAuth(http.HandlerFunc(a.saveRetention)))
	mux.Handle("POST /api/v1/traffic/reset", a.requireAuth(http.HandlerFunc(a.resetTraffic)))
	mux.Handle("POST /api/v1/storage/cleanup", a.requireAuth(http.HandlerFunc(a.cleanupStorage)))
	mux.Handle("POST /api/v1/ip-bans/preview", a.requireAuth(http.HandlerFunc(a.previewAccessRule)))
	mux.Handle("GET /api/v1/ip-bans/explain", a.requireAuth(http.HandlerFunc(a.explainAccessRules)))
	mux.Handle("POST /api/v1/ip-bans/guard/confirm", a.requireAuth(http.HandlerFunc(a.confirmAccessRule)))
	mux.Handle("POST /api/v1/ip-bans/guard/cancel", a.requireAuth(http.HandlerFunc(a.cancelAccessRule)))
	mux.Handle("GET /api/v1/config/backups", a.requireAuth(http.HandlerFunc(a.listRecoveryBackups)))
	static := web.Handler()
	mux.HandleFunc("GET /", func(w http.ResponseWriter, r *http.Request) {
		static.ServeHTTP(w, r)
	})
}
